/**
 * Converts a name into a URL-safe slug, e.g. "Lagos Logistics Ltd" → "lagos-logistics".
 */
export function slugify(name: string) {
  return name
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 50);
}
